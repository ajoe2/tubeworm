const assert = require("node:assert/strict")
const { formatBytes, formatSpeed, formatTime } = require("./load.cjs")("lib/format.ts")

assert.equal(formatTime(0), "0:00")
assert.equal(formatTime(65), "1:05")
assert.equal(formatTime(3725), "1:02:05")
assert.equal(formatTime(12.34, 1), "0:12.3")
assert.equal(formatTime(59.96, 1), "1:00.0", "rounding must carry into the minutes")
assert.equal(formatTime(-0.5, 1), "0:00.0")
assert.equal(formatTime(null), "—")
assert.equal(formatBytes(512), "512 B")
assert.equal(formatBytes(1536), "1.5 KiB")
assert.equal(formatBytes(150 * 1024 * 1024), "150 MiB")
assert.equal(formatSpeed(0), "—")
assert.equal(formatSpeed(2048), "2.0 KiB/s")
console.log("format: ok")
